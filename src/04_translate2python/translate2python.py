"""Stage 04 -- turn extracted equations into an executable Python module.

The LaTeX parser lives in stage 02 (``translator.py``).  This module re-exports
that API so ``from translate2python import translate`` still works, and writes
``equations.py`` from ``equations_raw.md``.

Typical use::

    from translate2python import translate
    eq = translate(r"h=1.45 k \\frac{\\tan \\theta}{\\sigma}"
                   r"\\left(\\frac{p}{H}\\right)^{0.985}")
    print(eq.python)          # h = 1.45*k*(p/H)**0.985*tan(theta)/sigma
    print(eq.evaluate(k=1, theta=0.1, sigma=2, p=3, H=4))

Run it with::

    python src/04_translate2python/translate2python.py
    python src/04_translate2python/translate2python.py --source src/01_input/sample_2.md
"""

