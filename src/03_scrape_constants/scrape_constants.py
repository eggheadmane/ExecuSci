def run(
    paper: Optional[str] = None,
    constants_path: str = DEFAULT_CONSTANTS_PATH,
    report_path: str = DEFAULT_REPORT_PATH,
    include_prose: bool = True,
    verbose: bool = True,
) -> List[Constant]:
    """Scrape ``paper`` and write ``constants.py`` and ``constants.md``."""
    path = paper or paper_path()
    with open(path, "r", encoding="utf-8") as fh:
        text = fh.read()

    # Stage 02 knows how the equations spell each symbol, which is what lets an
    # OCR-damaged table header be matched back to the symbol it was meant to be.
    equation_info = _load_equation_symbols()
    equation_symbols = set(equation_info)

    constants = extract_constants(
        text, include_prose=include_prose, equation_symbols=equation_symbols
    )
    source = generate_constants_module(
        text,
        module_doc=f"Constants scraped from {os.path.basename(path)}.",
        include_prose=include_prose,
        equation_symbols=equation_symbols,
        symbol_info=equation_info,
    )
    os.makedirs(os.path.dirname(os.path.abspath(constants_path)), exist_ok=True)
    os.makedirs(os.path.dirname(os.path.abspath(report_path)), exist_ok=True)
    with open(constants_path, "w", encoding="utf-8") as fh:
        fh.write(source)
    with open(report_path, "w", encoding="utf-8") as fh:
        fh.write(
            generate_report(
                text,
                source=path,
                include_prose=include_prose,
                equation_symbols=equation_symbols,
                symbol_info=equation_info,
            )
        )
    mirror_to_log(constants_path)

    if verbose:
        grouped = _organise(constants)
        print(f"Read {os.path.basename(path)}")
        print(
            f"  {len(grouped.shared)} shared constants, "
            f"{sum(len(v) for v in grouped.tools.values())} tool-specific, "
            f"{sum(len(v) for v in grouped.materials.values())} material properties"
        )
        if grouped.expressions:
            print(
                f"  {len(grouped.expressions)} temperature-dependent properties "
                "kept as expressions"
            )
        corrected = [c for c in constants if c.corrected_from]
        if corrected:
            print(
                "  repaired OCR-damaged names: "
                + ", ".join(f"{c.corrected_from} -> {c.name}" for c in corrected)
            )
        print(f"  wrote {constants_path}")
        print(f"  wrote {report_path}")

    return constants


def _parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Scrape the paper's constants and name them with SymPy symbols."
    )
    parser.add_argument(
        "--paper",
        default=None,
        help="Markdown/LaTeX source (default: the file in src/01_input/target/)",
    )
    parser.add_argument(
        "--constants",
        default=DEFAULT_CONSTANTS_PATH,
        help=f"Generated module path (default: {DEFAULT_CONSTANTS_PATH})",
    )
    parser.add_argument(
        "--report",
        default=DEFAULT_REPORT_PATH,
        help=f"Generated markdown report path (default: {DEFAULT_REPORT_PATH})",
    )
    parser.add_argument(
        "--no-prose",
        action="store_true",
        help="Only scrape tables, ignoring prose such as 'approximately 0.8'.",
    )
    return parser.parse_args(list(argv) if argv is not None else None)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _parse_args(argv)
    constants = run(
        paper=args.paper,
        constants_path=args.constants,
        report_path=args.report,
        include_prose=not args.no_prose,
    )
    return 0 if constants else 1


if __name__ == "__main__":
    raise SystemExit(main())
