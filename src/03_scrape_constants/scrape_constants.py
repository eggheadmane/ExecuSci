"""Stage 03 -- scrape every numeric constant the paper states and name it.

Each scraped value is given the same ASCII symbol name that ``latex2python``
generates for the equations (``\\lambda`` → ``lamda``, ``k_{s}`` → ``k_s``, …),
so the constants drop straight into the functions generated by stage 04.  The
generated module also builds a :class:`sympy.Symbol` for every name, so the
constants can be substituted into the symbolic form of the equations.

Sources
-------
1. **Symbol-keyed tables** (e.g. Table 3, "Material constants and model
   parameters"): header cell → symbol name, value cell → float.
2. **Property tables** (e.g. Table 2, "Material properties"), which are keyed by
   a property name per row and a material per column: ``Thermal conductivity``
   under ``P20`` → ``k`` for material ``P20``.  Temperature-dependent entries
   such as ``-39.082 T + 82532`` are recorded as expressions, not numbers.
3. **Prose** patterns such as ``$h_a$ ... approximately $0.8$``.

Run it with::

    python src/03_scrape_constants/scrape_constants.py
"""

