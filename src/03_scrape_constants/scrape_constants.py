def _load_equation_symbols() -> Dict[str, dict]:
    """Symbol dictionary written by stage 02, or ``{}`` if it has not run."""
    path = os.path.join(stage_dir("Extract Equations"), "output", "symbols.json")
    try:
        with open(path, "r", encoding="utf-8") as fh:
            return json.load(fh).get("symbols", {})
    except (OSError, ValueError):
        return {}


def _classify_symbol(
    name: str, info: dict, hits: Sequence[Constant]
) -> str:
    """``parameter``, ``material``, ``operating``, ``other``, or ``derived``."""
    if info.get("kind") == "derived":
        return "derived"
    if info.get("kind") == "parameter":
        return "parameter"
    if any(c.category == "material" for c in hits) or name in _MATERIAL_NAMES:
        return "material"
    description = info.get("description") or ""
    if name in _OPERATING_NAMES or _OPERATING_DESC_RE.search(description):
        return "operating"
    return "other"


def _operating_input_names(
    constants: Sequence[Constant], symbol_info: Dict[str, dict]
) -> List[str]:
    """Operating equation inputs the paper does not tabulate as numbers."""
    by_name: Dict[str, List[Constant]] = {}
    for constant in constants:
        by_name.setdefault(constant.name, []).append(constant)
    names: List[str] = []
    for name, info in sorted(symbol_info.items()):
        hits = by_name.get(name, [])
        if _classify_symbol(name, info, hits) != "operating":
            continue
        if any(c.is_numeric for c in hits):
            continue
        names.append(name)
    return names


def _fmt_value(value: Optional[float]) -> str:
    return "—" if value is None else f"{value:g}"


def generate_report(
    text: str,
    source: str = "",
    include_prose: bool = True,
    equation_symbols: Optional[Iterable[str]] = None,
    symbol_info: Optional[Dict[str, dict]] = None,
) -> str:
    """Render ``constants.md``: what was scraped, from where, and what is missing."""
    constants = extract_constants(
        text, include_prose=include_prose, equation_symbols=equation_symbols
    )
    grouped = _organise(constants)
    name = os.path.basename(source) or "the source document"
    corrected = [c for c in constants if c.corrected_from]

    lines: List[str] = [
        f"# Constants scraped from `{name}`",
        "",
        "Generated by ExecuSci stage 03 (`scrape_constants.py`). Do not edit by hand.",
        "",
        f"- Model constants and parameters: **{len(grouped.shared)}** shared, "
        f"**{sum(len(v) for v in grouped.tools.values())}** tool-specific",
        f"- Material properties: **{sum(len(v) for v in grouped.materials.values())}** "
        f"across {len(grouped.materials)} material(s)",
        f"- Temperature-dependent properties (left as expressions): "
        f"**{len(grouped.expressions)}**",
    ]
    if corrected:
        lines.append(
            f"- Names repaired after an OCR misread: **{len(corrected)}** "
            f"({', '.join(f'`{c.corrected_from}` -> `{c.name}`' for c in corrected)})"
        )
    lines.extend(
        [
            "",
            "## Model constants and parameters",
            "",
            "| Symbol | Name | Value | Unit | Tool | Source |",
            "| --- | --- | --- | --- | --- | --- |",
        ]
    )

    model = [c for c in constants if c.category == "model"]
    for c in sorted(model, key=lambda c: (c.name.lower(), c.variant or "")):
        source_bits = f"Table {c.table}" if c.table else c.source
        if c.source_line:
            source_bits += f" (line {c.source_line})"
        if c.corrected_from:
            source_bits += f", read as `{c.corrected_from}`"
        lines.append(
            f"| ${name_to_latex(c.name)}$ | `{c.name}` | {_fmt_value(c.value)} "
            f"| {c.unit or '—'} | {c.variant or '—'} | {source_bits} |"
        )

    lines.extend(["", "## Material properties", ""])
    if grouped.materials:
        lines.extend(
            [
                "| Material | Property | Symbol | Name | Value | Unit | Source |",
                "| --- | --- | --- | --- | --- | --- | --- |",
            ]
        )
        for material in sorted(grouped.materials):
            for key in sorted(grouped.materials[material]):
                c = grouped.materials[material][key]
                lines.append(
                    f"| {material} | {c.label or '—'} | ${name_to_latex(c.name)}$ "
                    f"| `{c.name}` | {_fmt_value(c.value)} | {c.unit or '—'} "
                    f"| Table {c.table} |"
                )
    else:
        lines.append("None found.")

    if grouped.expressions:
        lines.extend(
            [
                "",
                "## Temperature-dependent properties",
                "",
                "These are functions of temperature `T` (in K), not constants, so the "
                "paper's expression is kept instead of a number.",
                "",
                "| Material | Property | Expression | Unit | Source |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for c in grouped.expressions:
            expression = (c.expression or "").replace("|", "\\|")
            lines.append(
                f"| {c.variant} | {c.label or c.name} | {expression} "
                f"| {c.unit or '—'} | Table {c.table} |"
            )

    info = symbol_info if symbol_info is not None else _load_equation_symbols()
    if info:
        by_name: Dict[str, List[Constant]] = {}
        for constant in constants:
            by_name.setdefault(constant.name, []).append(constant)
        buckets: Dict[str, List[Tuple[str, dict, List[Constant]]]] = {
            "parameter": [],
            "material": [],
            "operating": [],
            "other": [],
        }
        for symbol_name, symbol in sorted(info.items()):
            bucket = _classify_symbol(
                symbol_name, symbol, by_name.get(symbol_name, [])
            )
            if bucket == "derived" or bucket not in buckets:
                continue
            buckets[bucket].append(
                (symbol_name, symbol, by_name.get(symbol_name, []))
            )

        lines.extend(
            [
                "",
                "## Coverage of the equation symbols",
                "",
                "Every symbol stage 02 found in the equations that is not itself "
                "computed by an equation, split into model parameters, material "
                "properties, and operating inputs (pressure, time, film thickness, …).",
            ]
        )
        sections = (
            (
                "parameter",
                "### Model parameters",
                "Fitted model parameters named in the paper's where-clauses.",
            ),
            (
                "material",
                "### Material properties",
                "Thermophysical or contact-body properties (tables or conventional names).",
            ),
            (
                "operating",
                "### Operating inputs",
                "Caller typically supplies these: contact pressure, time, temperature, "
                "speed, lubricant thickness.",
            ),
            (
                "other",
                "### Other inputs",
                "Remaining equation inputs that are not parameters, properties, or "
                "operating conditions.",
            ),
        )
        for key, heading, blurb in sections:
            rows = buckets[key]
            if key == "other" and not rows:
                continue
            lines.extend(["", heading, "", blurb, ""])
            if not rows:
                lines.append("None found.")
                continue
            lines.extend(
                [
                    "| Name | Needed by | Scraped value | Where |",
                    "| --- | --- | --- | --- |",
                ]
            )
            for symbol_name, symbol, hits in rows:
                used_in = ", ".join(symbol.get("used_in") or []) or "—"
                if not hits:
                    lines.append(
                        f"| `{symbol_name}` | {used_in} | — | supplied by caller |"
                    )
                    continue
                values = ", ".join(
                    f"{_fmt_value(c.value) if c.is_numeric else 'f(T)'}"
                    f"{f' ({c.variant})' if c.variant else ''}"
                    for c in hits
                )
                where = ", ".join(
                    sorted(
                        {
                            f"Table {c.table}" if c.table else c.source
                            for c in hits
                        }
                    )
                )
                lines.append(
                    f"| `{symbol_name}` | {used_in} | {values} | {where} |"
                )

    lines.append("")
    return "\n".join(lines)


