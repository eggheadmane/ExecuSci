@dataclass
class _Organised:
    """Scraped constants grouped the way the generated module lays them out."""

    shared: Dict[str, Constant]  # model constants with no variant
    tools: Dict[str, Dict[str, Constant]]  # model constants per tool material
    materials: Dict[str, Dict[str, Constant]]  # property-table values per material
    expressions: List[Constant]  # temperature-dependent properties


def _organise(constants: List[Constant]) -> _Organised:
    """Split into shared scalars, per-tool overrides and material properties."""
    shared: Dict[str, Constant] = {}
    tools: Dict[str, Dict[str, Constant]] = {}
    materials: Dict[str, Dict[str, Constant]] = {}
    expressions: List[Constant] = []
    for c in constants:
        if not c.is_numeric:
            expressions.append(c)
        elif c.category == "material":
            materials.setdefault(c.variant or "unknown", {})[c.name] = c
        elif c.variant:
            tools.setdefault(c.variant, {})[c.name] = c
        else:
            # First occurrence wins (tables usually precede prose).
            shared.setdefault(c.name, c)
    return _Organised(shared=shared, tools=tools, materials=materials, expressions=expressions)


def _fmt_float(x: float) -> str:
    """Render a float for generated source (keep scientific where natural)."""
    if x == 0:
        return "0.0"
    ax = abs(x)
    if ax >= 1e5 or (ax < 1e-3 and ax != 0):
        return f"{x:.6g}"
    # Prefer ordinary decimals for typical model params.
    s = f"{x:.12g}"
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0"
    return s


def generate_constants_module(
    text: str,
    *,
    module_doc: str = "",
    include_prose: bool = True,
    default_tool: Optional[str] = None,
    default_delta: float = 1.5e-5,
    equation_symbols: Optional[Iterable[str]] = None,
    symbol_info: Optional[Dict[str, dict]] = None,
) -> str:
    """Build a runnable ``constants.py`` source string from document ``text``.

    Layout mirrors the hand-authored plotting helper: ``_SHARED``, ``_TOOL``,
    and ``get_constants(tool, delta)`` so generated ``eq_*`` functions can be
    called with ``**get_constants()`` (or selected keys).
    """
    constants = extract_constants(
        text, include_prose=include_prose, equation_symbols=equation_symbols
    )
    grouped = _organise(constants)
    shared, tools = grouped.shared, grouped.tools

    doc = module_doc or "Auto-generated constants scraped from the paper by ExecuSci."
    lines: List[str] = [
        f'"""{doc}',
        "",
        "Names match symbols in the companion equations module (e.g. ``lamda``,",
        "``sigma_U``). Tool-specific values are grouped under ``_TOOL``, material",
        "property-table values under ``_MATERIAL``, and every name also exists as",
        "a SymPy symbol in ``SYMBOLS`` for substitution into symbolic equations.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from typing import Dict, List, Optional",
        "",
        "import sympy as sp",
        "",
        "# Shared blank / lubricant / model parameters (independent of tool material).",
        "_SHARED = {",
    ]

    for name in sorted(shared):
        c = shared[name]
        comment_bits = []
        if c.unit:
            comment_bits.append(c.unit)
        if c.table:
            comment_bits.append(f"Table {c.table}")
        elif c.source == "prose":
            comment_bits.append("prose")
        comment = f"  # {' — '.join(comment_bits)}" if comment_bits else ""
        lines.append(f'    "{name}": {_fmt_float(c.value)},{comment}')
    lines.append("}")
    lines.append("")

    lines.append("# Tool thermal conductivity and roughness by material.")
    lines.append("_TOOL = {")
    for tool in sorted(tools):
        lines.append(f'    "{tool}": {{')
        for name in sorted(tools[tool]):
            c = tools[tool][name]
            comment = f"  # Table {c.table}" if c.table else ""
            lines.append(f'        "{name}": {_fmt_float(c.value)},{comment}')
        lines.append("    },")
    lines.append("}")
    lines.append("")

    lines.append("# Thermophysical properties of each material, as printed by the paper.")
    lines.append("_MATERIAL = {")
    for material in sorted(grouped.materials):
        lines.append(f'    "{material}": {{')
        for name in sorted(grouped.materials[material]):
            c = grouped.materials[material][name]
            bits = [b for b in (c.label, c.unit, f"Table {c.table}" if c.table else None) if b]
            comment = f"  # {' — '.join(bits)}" if bits else ""
            lines.append(f'        "{name}": {_fmt_float(c.value)},{comment}')
        lines.append("    },")
    lines.append("}")
    lines.append("")

    if grouped.expressions:
        lines.append("# Properties the paper gives as functions of temperature T (in K).")
        lines.append("# They are not constants, so they are kept as the paper's expressions")
        lines.append("# rather than being turned into numbers.")
        lines.append("TEMPERATURE_DEPENDENT = {")
        for c in grouped.expressions:
            key = json.dumps(f"{c.variant}.{c.name}")
            expression = json.dumps(c.expression or "")
            label = f"  # {c.label}" if c.label else ""
            lines.append(f"    {key}: {expression},{label}")
        lines.append("}")
        lines.append("")

    if default_tool is None:
        # A paper that quotes no per-tool values has no default tool at all.
        default_tool = "P20" if "P20" in tools else next(iter(sorted(tools)), None)

    info = symbol_info if symbol_info is not None else _load_equation_symbols()
    operating = _operating_input_names(constants, info)
    if len(operating) == 1:
        operating_src = f'OPERATING_INPUTS = ("{operating[0]}",)'
    elif operating:
        operating_src = (
            "OPERATING_INPUTS = ("
            + ", ".join(f'"{n}"' for n in operating)
            + ")"
        )
    else:
        operating_src = "OPERATING_INPUTS = ()"

    lines.extend(
        [
            f'DEFAULT_TOOL = "{default_tool}"' if default_tool else "DEFAULT_TOOL = None",
            f"DEFAULT_DELTA = {_fmt_float(default_delta)}  # m — lubricant film thickness (user-supplied)",
            "",
            "# Equation inputs the paper does not tabulate (pressure, time, …).",
            "# Pass these when calling the generated eq_* functions.",
            operating_src,
            "",
            "# One SymPy symbol per scraped constant; the names are the ones the",
            "# generated equations use, so ``expr.subs(subs_map())`` just works.",
            "SYMBOLS: Dict[str, sp.Symbol] = {",
            "    name: sp.Symbol(name)",
            "    for name in sorted(",
            "        {*_SHARED, *(n for vals in _TOOL.values() for n in vals),",
            '         *(n for vals in _MATERIAL.values() for n in vals), "delta"}',
            "    )",
            "}",
            "",
            "",
            "def available_tools() -> List[str]:",
            '    """Tool materials the paper gives IHTC model constants for."""',
            "    return list(_TOOL.keys())",
            "",
            "",
            "def available_materials() -> List[str]:",
            '    """Materials the paper gives thermophysical properties for."""',
            "    return list(_MATERIAL.keys())",
            "",
            "",
            "def get_constants(tool: Optional[str] = DEFAULT_TOOL, delta: float = DEFAULT_DELTA) -> Dict[str, float]:",
            '    """Return a flat constant dict, per tool material where the paper gives one."""',
            "    if not _TOOL:",
            "        # This paper states no tool-specific values, so there is nothing to select.",
            '        return {**_SHARED, "delta": float(delta)}',
            "    if tool not in _TOOL:",
            "        raise ValueError(",
            '            f"Unknown tool {tool!r}. Choose from: {\', \'.join(available_tools())}"',
            "        )",
            '    consts = {**_SHARED, **_TOOL[tool], "delta": float(delta)}',
            "    return consts",
            "",
            "",
            "def material_properties(material: str) -> Dict[str, float]:",
            '    """Thermophysical properties (``E``, ``rho``, ``k``, …) of one material."""',
            "    if not _MATERIAL:",
            '        raise ValueError("This paper states no material property table")',
            "    if material not in _MATERIAL:",
            "        raise ValueError(",
            '            f"Unknown material {material!r}. Choose from: "',
            '            f"{\', \'.join(available_materials())}"',
            "        )",
            "    return dict(_MATERIAL[material])",
            "",
            "",
            "def symbol(name: str) -> sp.Symbol:",
            '    """The SymPy symbol scraped for ``name`` (e.g. ``symbol("k_s")``)."""',
            "    if name not in SYMBOLS:",
            "        raise KeyError(f\"No constant named {name!r} was scraped from the paper\")",
            "    return SYMBOLS[name]",
            "",
            "",
            "def subs_map(tool: Optional[str] = DEFAULT_TOOL, delta: float = DEFAULT_DELTA) -> Dict[sp.Symbol, float]:",
            '    """``{Symbol: value}`` substitution map for SymPy expressions."""',
            "    return {SYMBOLS[name]: float(value) for name, value in get_constants(tool, delta).items()}",
            "",
            "",
            "def as_dict() -> Dict[str, float]:",
            '    """All shared constants plus every tool-qualified name (``k_t_H13``, …)."""',
            "    out = {k: float(v) for k, v in _SHARED.items()}",
            "    for tool, vals in _TOOL.items():",
            '        for name, value in vals.items():',
            '            out[f"{name}_{tool}"] = float(value)',
            "    return out",
            "",
        ]
    )
    return "\n".join(lines)


