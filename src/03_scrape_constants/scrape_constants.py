# Prose extraction
# --------------------------------------------------------------------------- #

def _constants_from_prose(text: str) -> List[Constant]:
    out: List[Constant] = []
    seen: set = set()
    for m in _PROSE_CONST_RE.finditer(text):
        bridge = m.group("bridge")
        # Avoid matching equation definitions like $h = h_a + ...$.
        if "=" in bridge and "approximately" not in bridge.lower():
            # Allow "= approximately" style; skip pure equation bridges.
            if not re.search(r"approximately|approx|≈", bridge, re.I):
                continue
        name = latex_to_name(m.group("sym"))
        value = parse_number(m.group("val"))
        if name is None or value is None:
            continue
        key = (name, value)
        if key in seen:
            continue
        seen.add(key)
        out.append(
            Constant(
                name=name,
                value=value,
                source="prose",
                source_line=_line_of(text, m.start()),
                raw_header=m.group("sym").strip(),
                raw_value=m.group("val").strip(),
            )
        )
    return out


# --------------------------------------------------------------------------- #
# OCR reconciliation
# --------------------------------------------------------------------------- #

#: Characters Mathpix confuses in subscripts: ``\mu_{l0}`` is read as ``\mu_{10}``.
_CONFUSABLE = str.maketrans({"1": "l", "0": "o", "O": "o"})


def _confusion_key(name: str) -> str:
    """Fold OCR look-alikes together, so ``mu_10`` and ``mu_l0`` share a key."""
    return name.translate(_CONFUSABLE)


def reconcile_names(
    constants: List[Constant], equation_symbols: Optional[Iterable[str]]
) -> List[Constant]:
    """Repair scraped names that stage 01 misread, e.g. ``mu_10`` -> ``mu_l0``.

    A subscript ``l`` read as ``1`` gives a perfectly scraped *value* a name no
    equation uses, so it never reaches the generated functions.  A constant is
    only renamed when its own name matches no equation symbol and exactly one
    equation symbol looks identical once the look-alikes are folded together;
    the original spelling is kept in ``corrected_from`` for the report.
    """
    names = set(equation_symbols or ())
    if not names:
        return constants
    by_key: Dict[str, List[str]] = {}
    for symbol_name in names:
        by_key.setdefault(_confusion_key(symbol_name), []).append(symbol_name)

    for constant in constants:
        if constant.name in names:
            continue
        candidates = by_key.get(_confusion_key(constant.name), [])
        if len(candidates) != 1:
            continue
        constant.corrected_from, constant.name = constant.name, candidates[0]
    return constants


def extract_constants(
    text: str,
    *,
    include_prose: bool = True,
    equation_symbols: Optional[Iterable[str]] = None,
) -> List[Constant]:
    """Scrape constants from markdown tables (and optionally prose) in ``text``.

    ``equation_symbols`` (stage 02's symbol dictionary) enables the OCR name
    reconciliation described in :func:`reconcile_names`.
    """
    found: List[Constant] = []
    for table in extract_tables(text):
        found.extend(_constants_from_table(table, text))
    if include_prose:
        # Prefer table values when the same name already exists without a variant.
        table_names = {c.name for c in found if c.variant is None}
        for c in _constants_from_prose(text):
            if c.name in table_names:
                continue
            found.append(c)
    return reconcile_names(found, equation_symbols)


