def extract_tables(text: str) -> List[_MarkdownTable]:
    """Find pipe-style markdown tables and attach nearby ``Table N`` captions."""
    captions: List[Tuple[int, str, str]] = []
    for m in _TABLE_CAPTION_RE.finditer(text):
        title = (m.group("title") or "").strip()
        captions.append((m.start(), m.group("num"), title))

    tables: List[_MarkdownTable] = []
    lines = text.splitlines(keepends=True)
    # Rebuild with absolute offsets.
    offset = 0
    i = 0
    while i < len(lines):
        line = lines[i]
        if not _MD_TABLE_ROW_RE.match(line.rstrip("\n")):
            offset += len(line)
            i += 1
            continue

        block_start = offset
        row_lines: List[str] = []
        while i < len(lines) and _MD_TABLE_ROW_RE.match(lines[i].rstrip("\n")):
            row_lines.append(lines[i].rstrip("\n"))
            offset += len(lines[i])
            i += 1

        parsed_rows: List[List[str]] = []
        for rl in row_lines:
            m = _MD_TABLE_ROW_RE.match(rl)
            if not m:
                continue
            cells = [c.strip() for c in m.group("cells").split("|")]
            # Separator row (| :--- | :--- |).
            if all(_SEPARATOR_RE.match(c.replace(":", "-")) or not c for c in cells):
                continue
            if all(re.fullmatch(r":?-{3,}:?", c.replace(" ", "")) for c in cells if c):
                continue
            parsed_rows.append(cells)

        if len(parsed_rows) < 2:
            continue

        headers = parsed_rows[0]
        data = parsed_rows[1:]
        # Nearest caption before this table.
        table_num = caption = None
        for cap_pos, num, title in reversed(captions):
            if cap_pos < block_start:
                table_num, caption = num, title
                break
        tables.append(
            _MarkdownTable(
                headers=headers,
                rows=data,
                start=block_start,
                table_num=table_num,
                caption=caption,
            )
        )
    return tables


def _line_of(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


def _parse_header_row(
    cells: List[str],
) -> List[Tuple[Optional[str], Optional[str], Optional[str], str]]:
    return [(*_split_header(h), h) for h in cells]


def _row_symbol_score(cells: List[str]) -> Tuple[int, int]:
    """Return ``(symbol_hits, numeric_hits)`` for classifying header vs value rows."""
    symbols = 0
    numbers = 0
    for cell in cells:
        if not cell or not cell.strip():
            continue
        name, _, _ = _split_header(cell)
        num = parse_number(cell)
        # A pure number cell is a value; a parseable symbol (even if a number
        # substring exists inside units) counts as a header when named.
        if name is not None and not re.fullmatch(
            r"\$?\s*[+-]?\d+(?:\.\d+)?(?:\s*[eE]\s*[+-]?\d+)?\s*\$?",
            cell.strip(),
        ):
            # Prefer symbol if the cell is clearly math/identifier-heavy.
            if re.search(r"[\\_A-Za-z]", cell):
                symbols += 1
                continue
        if num is not None:
            numbers += 1
        elif name is not None:
            symbols += 1
    return symbols, numbers


def _row_is_header_like(cells: List[str]) -> bool:
    symbols, numbers = _row_symbol_score(cells)
    return symbols > 0 and symbols >= numbers


def _row_is_value_like(cells: List[str]) -> bool:
    symbols, numbers = _row_symbol_score(cells)
    return numbers > 0 and numbers >= symbols


def _emit_row_constants(
    parsed_headers: List[Tuple[Optional[str], Optional[str], Optional[str], str]],
    row: List[str],
    table: _MarkdownTable,
    text: str,
) -> List[Constant]:
    out: List[Constant] = []
    for col, (name, variant, unit, raw_h) in enumerate(parsed_headers):
        if name is None or col >= len(row):
            continue
        raw_v = row[col]
        value = parse_number(raw_v)
        if value is None:
            continue
        out.append(
            Constant(
                name=name,
                value=value,
                unit=unit,
                variant=variant,
                source="table",
                table=table.table_num,
                caption=table.caption,
                source_line=_line_of(text, table.start),
                raw_header=raw_h,
                raw_value=raw_v,
            )
        )
    return out


def _constants_from_table(table: _MarkdownTable, text: str) -> List[Constant]:
    """Pair symbol headers with numeric cells.

    Mathpix often emits "stacked" constant tables as **one** markdown table
    with alternating header / value rows (see Table 3).  Detect that pattern
    instead of treating every non-first row as values for the top header.
    """
    if _is_property_table(table):
        return _constants_from_property_table(table, text)

    if table.caption and _SKIP_CAPTION_RE.search(table.caption):
        if not _KEEP_CAPTION_RE.search(table.caption):
            return []

    # Build the sequence: markdown header row + body rows.
    all_rows: List[List[str]] = [table.headers, *table.rows]
    out: List[Constant] = []
    parsed_headers: Optional[
        List[Tuple[Optional[str], Optional[str], Optional[str], str]]
    ] = None
    symbol_header_blocks = 0

    for row in all_rows:
        if _row_is_header_like(row) and not _row_is_value_like(row):
            parsed_headers = _parse_header_row(row)
            named = sum(1 for n, _, _, _ in parsed_headers if n is not None)
            if named >= max(1, len([c for c in row if c.strip()]) // 2):
                symbol_header_blocks += 1
            else:
                parsed_headers = None
            continue

        if parsed_headers is None:
            continue

        if _row_is_value_like(row):
            out.extend(_emit_row_constants(parsed_headers, row, table, text))
            # Keep headers for a possible second value row; stacked tables
            # usually alternate, so the next header-like row will replace them.

    # Skip composition / property tables that never looked symbol-keyed.
    if symbol_header_blocks == 0:
        return []
    return out

# --------------------------------------------------------------------------- #
# Property tables (row = property, column = material)
# --------------------------------------------------------------------------- #

def _clean_unit(text: str) -> Optional[str]:
    """Turn a Mathpix unit fragment into something printable."""
    unit = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", text)
    unit = unit.replace("$", "").replace("~", "").replace("\\", "")
    unit = re.sub(r"\s+", "", unit).strip()
    return unit or None


def _clean_expression(text: str) -> str:
    """Strip Mathpix packaging from a temperature-dependent property cell.

    ``$\\begin{gathered} -5.145 \\mathrm{e}-08 \\mathrm{~T}^{2} \\\\ +0.085 \\end{gathered}$``
    becomes ``-5.145 e-08 T^{2} + 0.085``.
    """
    expression = text.strip().strip("$").strip()
    expression = re.sub(r"\\(?:begin|end)\{[^}]*\}", " ", expression)
    expression = expression.replace("\\\\", " ")
    expression = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", expression)
    expression = expression.replace("~", " ")
    return re.sub(r"\s+", " ", expression).strip()


def _normalize_material(label: str) -> Optional[str]:
    key = re.sub(r"[\s$]+", " ", label.strip().lower()).strip()
    key = re.sub(r"\\mathrm\{([^}]*)\}", r"\1", key)
    if not key:
        return None
    return _TOOL_ALIASES.get(key) or _MATERIAL_ALIASES.get(key.replace(" ", ""))


def _split_property_label(cell: str) -> Tuple[Optional[str], Optional[str], str]:
    """Return ``(symbol_name, unit, printed_label)`` for a property row label."""
    raw = re.sub(r"\s+", " ", cell.strip())
    unit = None
    match = re.search(r"\(([^)]*)\)\s*$", raw)
    label = raw
    if match:
        unit = _clean_unit(match.group(1))
        if unit in {"-", "—", "–", ""}:
            unit = None
        label = raw[: match.start()].strip()
    key = re.sub(r"[^a-z' ]+", "", label.lower()).strip()
    name = _PROPERTY_SYMBOLS.get(key)
    if name is None:
        name = next(
            (sym for prop, sym in _PROPERTY_SYMBOLS.items() if prop in key),
            None,
        )
    return name, unit, label


def _is_property_table(table: _MarkdownTable) -> bool:
    """True for tables keyed by a property per row and a material per column."""
    if not table.headers:
        return False
    first = re.sub(r"[^a-z ]+", "", table.headers[0].lower()).strip()
    if first not in _PROPERTY_HEADERS:
        return False
    return any(_normalize_material(h) for h in table.headers[1:])


def _constants_from_property_table(table: _MarkdownTable, text: str) -> List[Constant]:
    materials = [_normalize_material(h) for h in table.headers[1:]]
    out: List[Constant] = []
    for row in table.rows:
        if not row:
            continue
        name, unit, label = _split_property_label(row[0])
        if name is None:
            continue
        for column, material in enumerate(materials, start=1):
            if material is None or column >= len(row):
                continue
            raw_value = row[column]
            if not raw_value.strip():
                continue
            temperature_dependent = bool(_TEMPERATURE_RE.search(raw_value))
            value = None if temperature_dependent else parse_number(raw_value)
            if value is None and not temperature_dependent:
                continue
            out.append(
                Constant(
                    name=name,
                    value=value,
                    unit=unit,
                    variant=material,
                    source="table",
                    table=table.table_num,
                    caption=table.caption,
                    source_line=_line_of(text, table.start),
                    raw_header=table.headers[column],
                    raw_value=raw_value,
                    category="material",
                    label=label,
                    expression=_clean_expression(raw_value) if temperature_dependent else None,
                )
            )
    return out


